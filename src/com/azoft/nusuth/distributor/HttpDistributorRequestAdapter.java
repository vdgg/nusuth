    private void processCachedResponse(CachedElement page, boolean isNotModifiedResponse)
            throws DistributorException {
        if (logProxy.isDebugEnabled())
            logger.debug("Process cached response");
        state = PROCESSING_RESPONSE;
        responseLine.clear();
        cachedHeaders = (NusuthHeaders) page.getHeaders();
        if (isNotModifiedResponse) {
            responseLine.append(NOT_MODIFIED_RESPONSE_LINE);
            cachedHeaders.clearHeader(HttpConstants.CONTENT_LENGTH);
        } else {
            responseLine.append(OK_RESPONSE_LINE);
            cachedHeaders.putHeader(HttpConstants.CONTENT_LENGTH, String.valueOf(page.getBody().length).toCharArray());
        }
        cachedHeaders.putDateHeader(HTTP_LAST_MODIFIED, page.getLastModified());
        if (clientKeepAlive)
            cachedHeaders.putHeader(HttpConstants.CONNECTION, HttpConstants.KEEP_ALIVE);
        else
            cachedHeaders.putHeader(HttpConstants.CONNECTION, HttpConstants.CLOSE);

        if (!isNotModifiedResponse) {
            try {
                clientJSOS.write(page.getBody());
                logger.debug("Cached response body writed sucessfully");
            } catch (IOException ioex) {
                throw new DistributorException("Couldn't write cached response", ioex, ERROR_BadResponse);
            }
        }

        try {
            clientJSOS.close();
            logger.debug("Cached response flushed sucessfully");
        } catch (InterruptedIOException inex) {
            throw new DistributorException("Output stream timeout", inex, ERROR_BadClientSocket);
        } catch (IOException ioex) {
            throw new DistributorException("Couldn't flush output stream", ioex, ERROR_BadClientSocket);
        }
    }

    private void processMergedResponse(CachedElement page)
            throws DistributorException {
        if (logProxy.isDebugEnabled())
            logger.debug("Process merged response for \"" + page.getUrl() + '"');
        responseIsCacheable = responseHeaders.containsHeader(FileServlet.FILE_SERVLET_HEADER_NAME) && responseHeaders.getIntHeader(HTTP_CONTENT_LENGTH) < cache.getMaxPageSize();
        responseHeaders.clearHeader(FileServlet.FILE_SERVLET_HEADER_NAME);
        boolean isResponseKeepAilve = responseHeaders.containsHeader(HttpConstants.CONNECTION, HttpConstants.KEEP_ALIVE);
        boolean isChunked = responseHeaders.containsHeader(HttpConstants.TRANSFER_ENCODING, HttpConstants.CHUNKED);
        if (isResponseKeepAilve != clientKeepAlive)
            responseHeaders.putHeader(HttpConstants.CONNECTION, clientKeepAlive ? HttpConstants.KEEP_ALIVE : HttpConstants.CLOSE);
        if (!clientKeepAlive)
            responseHeaders.clearHeader(HttpConstants.TRANSFER_ENCODING);
        if (isChunked) {
            CIS.init(containerHSIS);
            readAllFromContainer(CIS);
            CIS.cleanup();
        } else {
            int contentLength = -1;
            try {
                contentLength = Utils.retreiveContentLength(responseHeaders);
            } catch (IOException ioex) {
                throw new DistributorException("Couldn't retrieve response content length", ioex, ERROR_BadResponse);
            }

            if (contentLength > -1) { // fixed content length
                if (contentLength != 0) {
                    FIS.init(containerHSIS, contentLength);
                    readAllFromContainer(FIS);
                    FIS.cleanup();
                }
            } else {
                throw new DistributorException("Couldn't define response content length", null, ERROR_BadResponse);
            }
        }

        processCachedResponse(page, false);
    }
