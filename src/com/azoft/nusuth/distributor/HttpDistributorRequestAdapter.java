    public void processError(int errorCode, String message) {
        int httpErr = 0;
        switch (errorCode) {
            case OK:
                return;
            case ERROR_BadClientSocket:
                return;
            case ERROR_BadRequest:
                httpErr = 400;
                break;
            case ERROR_NotFound:
                httpErr = 404;
                break;
            default :
                httpErr = 500;
                break;
        }

        try {
            if (logProxy.isDebugEnabled())
                logger.debug("Sending http error #" + httpErr + " at " + Thread.currentThread().getName());
            NusuthServletOutputStream jbirdOutputStream = new NusuthServletOutputStream(clientSocket.getOutputStream());
            HttpNusuthResponse response = new HttpNusuthResponse(jbirdOutputStream);
            response.init(jbirdOutputStream, false);
            if (logProxy.isDebugEnabled())
                response.sendError(httpErr, "Internal error #" + errorCode + ", message \"" + message + "\", thread " + Thread.currentThread().getName());
            else
                response.sendError(httpErr, message);
        } catch (IOException ioex) {
            logger.error("Couldn't send error " + httpErr, ioex);
        }
    }

